import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { defineConfig, type Plugin } from "vite";

const OUT = "custom_components/homeslice/frontend";

// Home Assistant loads homeslice.js from a URL that only changes on restart. The loader
// fetches version.json (never cached) and imports the real bundle by its content hash,
// so a new deploy shows up on the next page load and unchanged bundles stay cached.
const loaderFor = (bundle: string) => `// Generated by vite.config.ts: loads the current Homeslice bundle.
const base = new URL(".", import.meta.url);
const { v } = await (await fetch(new URL("version.json", base), { cache: "no-store" })).json();
await import(new URL(\`${bundle}?v=\${v}\`, base).href);
`;

function loader(): Plugin {
  return {
    name: "homeslice-loader",
    closeBundle() {
      // one version for both bundles (their shared chunks have hashed names anyway)
      const hash = createHash("sha256");
      for (const f of ["homeslice-app.js", "homeslice-editor.js"]) hash.update(readFileSync(`${OUT}/${f}`));
      const v = hash.digest("hex").slice(0, 12);
      writeFileSync(`${OUT}/version.json`, JSON.stringify({ v }) + "\n");
      // dashboards load the card; the sidebar page loads the editor
      writeFileSync(`${OUT}/homeslice.js`, loaderFor("homeslice-app.js"));
      writeFileSync(`${OUT}/homeslice-panel.js`, loaderFor("homeslice-editor.js"));
    },
  };
}

export default defineConfig({
  plugins: [loader()],
  publicDir: "assets",
  build: {
    minify: true,
    outDir: OUT,
    // assets/ (the furniture models) is copied next to the bundles
    copyPublicDir: true,
    emptyOutDir: true,
    sourcemap: true,
    target: "es2022",
    lib: {
      entry: { "homeslice-app": "frontend/main.ts", "homeslice-editor": "frontend/editor-main.ts" },
      formats: ["es"],
      fileName: (_format, name) => `${name}.js`,
    },
  },
  test: {
    include: ["frontend/**/*.test.ts"],
  },
});
