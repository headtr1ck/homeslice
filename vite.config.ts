import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { defineConfig, type Plugin } from "vite";

const OUT = "custom_components/homeslice/frontend";

// Home Assistant loads homeslice.js from a URL that only changes on restart. The loader
// fetches version.json (never cached) and imports the real bundle by its content hash,
// so a new deploy shows up on the next page load and unchanged bundles stay cached.
const LOADER = `// Generated by vite.config.ts: loads the current Homeslice bundle.
const base = new URL(".", import.meta.url);
const { v } = await (await fetch(new URL("version.json", base), { cache: "no-store" })).json();
await import(new URL(\`homeslice-app.js?v=\${v}\`, base).href);
`;

function loader(): Plugin {
  return {
    name: "homeslice-loader",
    closeBundle() {
      const app = readFileSync(`${OUT}/homeslice-app.js`);
      const v = createHash("sha256").update(app).digest("hex").slice(0, 12);
      writeFileSync(`${OUT}/version.json`, JSON.stringify({ v }) + "\n");
      writeFileSync(`${OUT}/homeslice.js`, LOADER);
    },
  };
}

export default defineConfig({
  plugins: [loader()],
  build: {
    minify: true,
    outDir: OUT,
    emptyOutDir: true,
    sourcemap: true,
    target: "es2022",
    lib: {
      entry: "frontend/main.ts",
      formats: ["es"],
      fileName: () => "homeslice-app.js",
    },
  },
  test: {
    include: ["frontend/**/*.test.ts"],
  },
});
